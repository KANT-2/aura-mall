"""Generate db/seed.sql from the web Mock catalog so IDs and prices stay identical.

Run from the repository root after the fixture changes:
    python apps/api/db/generate_seed.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATALOG = ROOT / "apps/web/mock-server/fixtures/catalog.json"
OUTPUT = Path(__file__).with_name("seed.sql")


def text(value: str | None) -> str:
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def text_array(values: list[str] | None) -> str:
    if values is None:
        return "NULL"
    return "ARRAY[" + ", ".join(text(v) for v in values) + "]::text[]" if values else "'{}'"


def jsonb(value: object) -> str:
    return "NULL" if value is None else text(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def boolean(value: bool) -> str:
    return "true" if value else "false"


def number(value: int | None) -> str:
    return "NULL" if value is None else str(int(value))


def insert(table: str, columns: list[str], rows: list[list[str]], conflict: str) -> str:
    values = ",\n".join("    (" + ", ".join(row) + ")" for row in rows)
    return (
        f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values}\n"
        f"ON CONFLICT {conflict} DO NOTHING;\n"
    )


def build(catalog: dict) -> str:
    types = {t["id"]: t for t in catalog["types"]}
    bestsellers = {pid: rank for rank, pid in enumerate(catalog["home"]["bestsellerIds"], 1)}
    for product in catalog["products"]:
        # typeName is derived from product_types.name, so the two must agree.
        if types[product["type"]]["name"] != product["typeName"]:
            raise SystemExit(f"typeName mismatch for {product['id']}")

    parts = [
        "-- AURA initial data. GENERATED by db/generate_seed.py from\n"
        "-- apps/web/mock-server/fixtures/catalog.json — edit the fixture, then regenerate.\n"
        "-- Safe to run more than once (existing rows are kept). No accounts are created:\n"
        "-- admins are granted through an operations step, not a default password.\n",
        "BEGIN;\n",
        insert(
            "collections",
            ["id", "name", "title", "description", "color", "notes", "sort_order"],
            [
                [
                    text(c["id"]),
                    text(c["name"]),
                    text(c["title"]),
                    text(c["description"]),
                    text(c["color"]),
                    text_array(c["notes"]),
                    str(i),
                ]
                for i, c in enumerate(catalog["collections"])
            ],
            "(id)",
        ),
        insert(
            "product_types",
            ["id", "name", "label", "sort_order"],
            [
                [text(t["id"]), text(t["name"]), text(t["label"]), str(i)]
                for i, t in enumerate(catalog["types"])
            ],
            "(id)",
        ),
        insert(
            "products",
            [
                "id",
                "collection_id",
                "type_id",
                "name",
                "english_name",
                "volume",
                "price",
                "stock",
                "image",
                "image_url",
                "description",
                "category",
                "notes",
                "note_images",
                "gift_images",
                "featured",
                "is_new",
                "bestseller_rank",
                "sort_order",
            ],
            [
                [
                    text(p["id"]),
                    text(p["collection"]),
                    text(p["type"]),
                    text(p["name"]),
                    text(p["englishName"]),
                    text(p["volume"]),
                    number(p["price"]),
                    number(p["stock"]),
                    text(p["image"]),
                    text(p["imageUrl"]),
                    text(p["description"]),
                    text(p["category"]),
                    text_array(p["notes"]),
                    jsonb(p.get("noteImages")),
                    text_array(p.get("giftImages")),
                    boolean(p["featured"]),
                    boolean(p["isNew"]),
                    number(bestsellers.get(p["id"])),
                    str(i),
                ]
                for i, p in enumerate(catalog["products"])
            ],
            "(id)",
        ),
        insert(
            "ingredients",
            ["id", "name", "stage", "color", "description", "sort_order"],
            [
                [
                    text(g["id"]),
                    text(g["name"]),
                    text(g["stage"]),
                    text(g["color"]),
                    text(g["description"]),
                    str(i),
                ]
                for i, g in enumerate(catalog["ingredients"])
            ],
            "(id)",
        ),
        insert(
            "scent_families",
            ["id", "name", "english", "asset", "description", "sort_order"],
            [
                [
                    text(f["id"]),
                    text(f["name"]),
                    text(f["english"]),
                    text(f["asset"]),
                    text(f["description"]),
                    str(i),
                ]
                for i, f in enumerate(catalog["scentFamilies"])
            ],
            "(id)",
        ),
        insert(
            "scent_family_ingredients",
            ["family_id", "ingredient_id", "position"],
            [
                [text(f["id"]), text(note), str(i)]
                for f in catalog["scentFamilies"]
                for i, note in enumerate(f["notes"])
            ],
            "(family_id, ingredient_id)",
        ),
        insert(
            "suggested_names",
            ["collection_id", "name", "sort_order"],
            [
                [text(collection), text(name), str(i)]
                for collection, names in catalog["atelier"]["suggestedNames"].items()
                for i, name in enumerate(names)
            ],
            "(collection_id, name)",
        ),
        insert(
            "promotions",
            ["audience", "title", "copy", "cta", "url", "image", "sort_order"],
            [
                [
                    text(audience),
                    text(p["title"]),
                    text(p["copy"]),
                    text(p["cta"]),
                    text(p["url"]),
                    text(p["image"]),
                    str(i),
                ]
                for audience, key in (("guest", "guestPromotions"), ("member", "memberPromotions"))
                for i, p in enumerate(catalog["home"][key])
            ],
            "(audience, sort_order)",
        ),
        "COMMIT;\n",
    ]
    return "\n".join(parts)


def main() -> None:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    OUTPUT.write_text(build(catalog), encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {OUTPUT.relative_to(ROOT)}\n")


if __name__ == "__main__":
    main()
